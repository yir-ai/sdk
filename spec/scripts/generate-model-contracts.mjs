import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const repositoryRoot = packageRoot;
const artifactPath = path.resolve(repositoryRoot, "spec/models.json");
const openAPIPath = path.resolve(repositoryRoot, "spec/openapi.json");
const typeScriptOutputPath = path.resolve(packageRoot, "typescript/src/shared/generated/model-contracts.generated.ts");
const goOutputPath = path.resolve(packageRoot, "go/model_contracts_generated.go");
const checkOnly = process.argv.includes("--check");


const artifact = JSON.parse(await readFile(artifactPath, "utf8"));
const openAPI = JSON.parse(await readFile(openAPIPath, "utf8"));
validateArtifact(artifact, openAPI);

const serializedArtifact = JSON.stringify(artifact, null, 2);
const generatedTypeScript = [
  "// Generated by scripts/generate-model-contracts.mjs. Do not edit manually.",
  'import type { ModelContractCatalog } from "../model-contracts.js";',
  "",
  `export const generatedModelContractCatalog = ${serializedArtifact} as const satisfies ModelContractCatalog;`,
  "",
].join("\n");

assert(!serializedArtifact.includes("`"), "model contract artifact cannot contain a Go raw-string delimiter");
const generatedGo = [
  "// Code generated by scripts/generate-model-contracts.mjs. DO NOT EDIT.",
  "",
  "package yir",
  "",
  "const generatedModelContractCatalogJSON = `" + serializedArtifact + "`",
  "",
].join("\n");


const outputs = [
  [typeScriptOutputPath, generatedTypeScript],
  [goOutputPath, generatedGo],
];

if (checkOnly) {
  const stale = [];
  for (const [outputPath, generated] of outputs) {
    const current = await readFile(outputPath, "utf8").catch(() => "");
    if (current !== generated) stale.push(path.relative(packageRoot, outputPath));
  }
  if (stale.length > 0) {
    throw new Error(`generated model contracts are stale: ${stale.join(", ")}; run pnpm generate:model-contracts`);
  }
} else {
  for (const [outputPath, generated] of outputs) {
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, generated, "utf8");
  }
}

function validateArtifact(catalog, specification) {
  assert(catalog?.schema_version === "v1", "model contract schema_version must be v1");
  assert(
    catalog?.schema_ref === "./openapi.json#/components/schemas/ModelContractCatalog",
    "model contract schema_ref must target Standard OpenAPI",
  );
  assert(specification?.openapi === "3.1.0", "Standard OpenAPI must use version 3.1.0");
  assert(
    specification?.components?.schemas?.ModelContractCatalog,
    "Standard OpenAPI must define ModelContractCatalog",
  );
  assert(Array.isArray(catalog.models) && catalog.models.length > 0, "model contracts must not be empty");

  const identities = new Set();
  for (const model of catalog.models) {
    assert(typeof model.id === "string" && model.id.includes("/"), "model id must be canonical");
    assertLocalized(model.locales, `model ${model.id}`);
    for (const identity of [model.id, ...(model.aliases ?? [])]) {
      assert(!identities.has(identity), `duplicate model identity ${identity}`);
      identities.add(identity);
    }
    assert(Array.isArray(model.operations) && model.operations.length > 0, `${model.id} needs operations`);
    for (const operation of model.operations) validateOperation(model, operation, specification);
  }
}

function validateOperation(model, operation, specification) {
  const prefix = "#/components/schemas/";
  assert(operation.request_schema?.startsWith(prefix), `${model.id} request_schema must be local`);
  const schemaName = operation.request_schema.slice(prefix.length);
  const schema = specification.components.schemas[schemaName];
  assert(schema?.type === "object", `${model.id} request schema ${schemaName} is missing`);
  assert(Array.isArray(operation.input_modes) && operation.input_modes.length > 0, `${model.id} needs input modes`);
  assert(operation.input_constraints && typeof operation.input_constraints === "object", `${model.id} needs input constraints`);
  assert(
    Object.keys(operation.input_constraints).length === operation.input_modes.length,
    `${model.id} input constraint count drift`,
  );
  for (const inputMode of operation.input_modes) {
    const constraint = operation.input_constraints[inputMode];
    assert(constraint, `${model.id}.${inputMode} constraint missing`);
    assert(constraint.min_references >= 0, `${model.id}.${inputMode} minimum references invalid`);
    assert(constraint.max_references >= constraint.min_references, `${model.id}.${inputMode} reference range invalid`);
    assert(Array.isArray(constraint.allowed_reference_roles), `${model.id}.${inputMode} roles missing`);
    for (const role of constraint.required_reference_roles ?? []) {
      assert(constraint.allowed_reference_roles.includes(role), `${model.id}.${inputMode} required role is not allowed`);
    }
    for (const [role, limit] of Object.entries(constraint.reference_counts_by_role ?? {})) {
      assert(constraint.allowed_reference_roles.includes(role), `${model.id}.${inputMode} count role is not allowed`);
      assert(Number.isSafeInteger(limit.minimum) && limit.minimum >= 0 && Number.isSafeInteger(limit.maximum) && limit.maximum >= limit.minimum,
        `${model.id}.${inputMode} role count range invalid`);
    }
    for (const role of constraint.required_any_reference_roles ?? []) {
      assert(constraint.allowed_reference_roles.includes(role), `${model.id}.${inputMode} alternative role is not allowed`);
    }
    for (const [role, maximum] of Object.entries(constraint.max_duration_by_reference_role ?? {})) {
      assert(constraint.allowed_reference_roles.includes(role) && Number.isSafeInteger(maximum) && maximum > 0,
        `${model.id}.${inputMode} reference duration limit invalid`);
    }
  }
  assert(Array.isArray(operation.parameters) && operation.parameters.length > 0, `${model.id} needs parameters`);

  const parameterSchema = schema.properties?.parameters;
  assert(parameterSchema?.type === "object", `${model.id} parameters must be a nested object`);
  const required = new Set(parameterSchema.required ?? []);
  const names = new Set();
  for (const parameter of operation.parameters) {
    assert(!names.has(parameter.name), `${model.id} has duplicate parameter ${parameter.name}`);
    names.add(parameter.name);
    const property = parameterSchema.properties?.[parameter.name];
    assert(property, `${model.id} parameter ${parameter.name} is absent from ${schemaName}`);
    assert(property.type === parameter.type, `${model.id} parameter ${parameter.name} type drift`);
    assert(!parameter.required || parameter.default !== undefined || required.has(parameter.name), `${model.id} parameter ${parameter.name} missing default or required constraint`);
    assertLocalized(parameter.locales, `${model.id}.${parameter.name}`);
    if (parameter.policy !== undefined) {
      for (const key of ["only_provider", "reason", "message"]) {
        assert(typeof parameter.policy[key] === "string" && parameter.policy[key].trim(), `${model.id}.${parameter.name} policy ${key} missing`);
      }
    }
    if (parameter.values !== undefined) {
      assert(Array.isArray(parameter.values) && parameter.values.length > 0, `${model.id}.${parameter.name} values empty`);
      assert(new Set(parameter.values.map(String)).size === parameter.values.length, `${model.id}.${parameter.name} values duplicate`);
      for (const value of parameter.values) validateValue(model.id, parameter.name, value, property);
      if (parameter.default !== undefined) {
        assert(parameter.values.includes(parameter.default), `${model.id}.${parameter.name} default outside values`);
      }
    }
    if (parameter.minimum !== undefined) {
      assert(property.minimum === undefined || parameter.minimum >= property.minimum, `${model.id}.${parameter.name} minimum outside OpenAPI`);
      assert(parameter.default >= parameter.minimum, `${model.id}.${parameter.name} default below minimum`);
    }
    if (parameter.maximum !== undefined) {
      assert(property.maximum === undefined || parameter.maximum <= property.maximum, `${model.id}.${parameter.name} maximum outside OpenAPI`);
      assert(parameter.default <= parameter.maximum, `${model.id}.${parameter.name} default above maximum`);
    }
  }
}

function validateValue(modelID, name, value, schema) {
  if (schema.enum) assert(schema.enum.includes(value), `${modelID}.${name} value ${value} is outside OpenAPI enum`);
  if (typeof value === "number") {
    if (schema.minimum !== undefined) assert(value >= schema.minimum, `${modelID}.${name} below minimum`);
    if (schema.maximum !== undefined) assert(value <= schema.maximum, `${modelID}.${name} above maximum`);
  }
  if (typeof value === "string" && schema.minLength !== undefined) {
    assert(value.length >= schema.minLength, `${modelID}.${name} shorter than minLength`);
  }
}

function assertLocalized(locales, subject) {
  for (const locale of ["en", "zh-CN"]) {
    assert(locales?.[locale]?.label, `${subject} is missing ${locale} label`);
    assert(locales?.[locale]?.description, `${subject} is missing ${locale} description`);
  }
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}
